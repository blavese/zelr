"""The font, drawn by hand, and the two files it gets emitted into.

This used to render Consolas through PIL and threshold the result, which made
the glyph shapes somebody else's and put a Python imaging library in the way
of building a font. Every glyph below is drawn here instead, as text art, so
the shapes are the project's own and editing one means editing a picture of
it.

The cell is 8 wide and 16 tall. Within that:

    rows 0-2    empty, so a line of text has air above it
    rows 3-11   capitals and ascenders, nine rows
    rows 6-11   x-height, six rows
    row  11     the baseline: the last row a capital puts ink on
    rows 12-14  descenders
    row  15     empty

Stems are one pixel. At sixteen pixels tall a two pixel stem reads as bold,
and the console is small enough already.

Each entry is (first row, rows). Anything not listed is a blank cell.

  python tools/genfont.py        writes kernel/font.c and userland/font.h
  python tools/genfont.py -p     prints a sample instead
"""
