# --- turning the art into bits -------------------------------------------

def build(ch):
    """One glyph as sixteen bytes, high bit leftmost."""
    rows = [0] * CELL_H
    if ch not in GLYPHS:
        raise SystemExit("no glyph drawn for %r" % ch)

    top, art = GLYPHS[ch]
    for i, line in enumerate(art):
        y = top + i
        if y >= CELL_H:
            raise SystemExit("%r runs past the bottom of the cell" % ch)
        if len(line) != CELL_W:
            raise SystemExit("%r row %d is %d wide, not %d"
                             % (ch, i, len(line), CELL_W))
        bits = 0
        for x, c in enumerate(line):
            if c == "#":
                bits |= 1 << (CELL_W - 1 - x)
            elif c != ".":
                raise SystemExit("%r row %d has %r in it" % (ch, i, c))
        rows[y] = bits
    return rows


def preview(glyphs, text):
    """The font as text art, so it can be looked at before it is trusted."""
    lines = [""] * CELL_H
    for ch in text:
        g = glyphs[ord(ch) - FIRST]
        for y in range(CELL_H):
            lines[y] += "".join("#" if g[y] & (1 << (CELL_W - 1 - x)) else "."
                                for x in range(CELL_W))
    return "\n".join(lines)


def main():
    missing = [c for c in range(FIRST, LAST + 1) if chr(c) not in GLYPHS]
    if missing:
        raise SystemExit("undrawn: %s" % " ".join(repr(chr(c)) for c in missing))

    glyphs = [build(chr(c)) for c in range(FIRST, LAST + 1)]
    total = LAST - FIRST + 1

    inked = sum(1 for g in glyphs if any(g))
    print("%d glyphs, %d with ink (space is legitimately blank)"
          % (total, inked), file=sys.stderr)

    if "-p" in sys.argv:
        for sample in ("zelr> Hello 123", "The quick brown fox",
                       "jumps over {a} [lazy] dog!", "0O1lI |#@%&*_+=~"):
            print(preview(glyphs, sample))
            print()
        return 0

    out = ["/* Generated by tools/genfont.py. Do not edit by hand;",
           "   edit the pictures in that file instead. */",
           '#include "font.h"', ""]
    out.append("const u8 font8x16[%d][%d] = {" % (total, CELL_H))
    for i, g in enumerate(glyphs):
        body = ", ".join("0x%02X" % b for b in g)
        out.append("    { %s },   /* %3d %r */" % (body, FIRST + i, chr(FIRST + i)))
    out.append("};")
    out.append("")
    open("kernel/font.c", "w").write("\n".join(out))
    print("wrote kernel/font.c", file=sys.stderr)

    # The same glyphs again, as a header. Ring 3 shares nothing with the
    # kernel, so a program that wants to draw text needs its own copy.
    u = ["/* Generated by tools/genfont.py. Do not edit by hand. */",
         "#pragma once", "",
         "#define FONT_W %d" % CELL_W,
         "#define FONT_H %d" % CELL_H,
         "#define FONT_FIRST %d" % FIRST,
         "#define FONT_LAST  %d" % LAST, ""]
    u.append("static const unsigned char font8x16[%d][%d] = {" % (total, CELL_H))
    for g in glyphs:
        u.append("    { %s }," % ", ".join("0x%02X" % b for b in g))
    u.append("};")
    u.append("")
    open("userland/font.h", "w").write("\n".join(u))
    print("wrote userland/font.h", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
