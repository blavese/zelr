"""Makes userland/zipdata.h: archives for userland/ziptest.c to read.

They are written by Python's own zipfile and zlib, not by anything in this
tree, for the same reason pngtest's pictures are: a reader checked against
its own writer agrees with itself and proves nothing. Then a few are spoiled
on purpose, a byte or a field each, for the reader to refuse by name.

  ARC_GOOD     a deflated file, a folder with a stored file and a deflated
               one, the folder's own entry, and a comment after the end;
  ARC_STREAM   the same files written as a stream: each local header has
               no sizes (bit 3) and they are in the central directory only;
  ARC_CRC      ARC_GOOD with a byte of its stored file changed;
  ARC_METHOD   ARC_GOOD with its first file said to be bzip2 (12);
  ARC_LOCKED   ARC_GOOD with its first file said to be locked (flag bit 0);
  ARC_CUT      ARC_GOOD with its end record cut off.

The files' own bytes are written too, for the reader's to be compared
with. Every timestamp is fixed, so the header comes out the same each run.

  python tools/genzip.py
"""
import io
import os
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "userland", "zipdata.h")
WHEN = (2026, 11, 20, 12, 0, 0)

README = b"".join(b"line %d of a file that compresses well, as text does\n" % i for i in range(60))
A_TXT = b"stored as it is, the second file\n"
B_TXT = b"deflated, in a folder\n" * 20
FILES = [("readme.txt", README, zipfile.ZIP_DEFLATED),
         ("notes/a.txt", A_TXT, zipfile.ZIP_STORED),
         ("notes/b.txt", B_TXT, zipfile.ZIP_DEFLATED)]


def write(z):
    d = zipfile.ZipInfo("notes/", WHEN)
    d.external_attr = 0o40755 << 16 | 0x10
    for name, data, how in FILES[:1]:
        i = zipfile.ZipInfo(name, WHEN)
        i.compress_type = how
        z.writestr(i, data)
    z.writestr(d, b"")
    for name, data, how in FILES[1:]:
        i = zipfile.ZipInfo(name, WHEN)
        i.compress_type = how
        z.writestr(i, data)


def good():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        write(z)
        z.comment = b"a comment after the end, which the reader has to look past"
    return buf.getvalue()


class Unseekable(io.RawIOBase):
    """A stream zipfile cannot go back in, so it writes data descriptors."""
    def __init__(self):
        self.out = bytearray()

    def writable(self):
        return True

    def write(self, b):
        self.out += b
        return len(b)


def stream():
    s = Unseekable()
    with zipfile.ZipFile(s, "w") as z:
        write(z)
    return bytes(s.out)


def local_of(data, name):
    """Where a file's local header is, from the central directory."""
    z = zipfile.ZipFile(io.BytesIO(data))
    return z.getinfo(name).header_offset


def central_of(data, name):
    at = data.index(b"PK\x01\x02")
    while at >= 0:
        nlen = int.from_bytes(data[at + 28:at + 30], "little")
        if data[at + 46:at + 46 + nlen] == name.encode():
            return at
        at = data.find(b"PK\x01\x02", at + 46)
    raise SystemExit("no central entry for " + name)


def spoiled(data, how):
    d = bytearray(data)
    if how == "crc":
        lo = local_of(data, "notes/a.txt")
        nlen = int.from_bytes(d[lo + 26:lo + 28], "little")
        xlen = int.from_bytes(d[lo + 28:lo + 30], "little")
        d[lo + 30 + nlen + xlen + 3] ^= 0x20
    elif how == "method":
        lo, ce = local_of(data, "readme.txt"), central_of(data, "readme.txt")
        d[lo + 8:lo + 10] = (12).to_bytes(2, "little")
        d[ce + 10:ce + 12] = (12).to_bytes(2, "little")
    elif how == "locked":
        lo, ce = local_of(data, "readme.txt"), central_of(data, "readme.txt")
        d[lo + 6] |= 1
        d[ce + 8] |= 1
    elif how == "cut":
        d = d[:data.rindex(b"PK\x05\x06")]
    return bytes(d)


def array(name, data, note):
    lines = ["/* %s: %d bytes */" % (note, len(data)), "static const u8 %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    g = good()
    parts = [
        "/* Generated by tools/genzip.py. Do not edit by hand.\n\n"
        "   Archives for userland/ziptest.c to read, made by Python's zipfile\n"
        "   and zlib, and some spoiled on purpose. See that script for each. */",
        "#pragma once",
        '#include "zelr.h"',
        array("ARC_GOOD", g, "three files, a folder and a comment"),
        array("ARC_STREAM", stream(), "the same, written as a stream (data descriptors)"),
        array("ARC_CRC", spoiled(g, "crc"), "a byte of notes/a.txt changed"),
        array("ARC_METHOD", spoiled(g, "method"), "readme.txt said to be bzip2"),
        array("ARC_LOCKED", spoiled(g, "locked"), "readme.txt said to be locked"),
        array("ARC_CUT", spoiled(g, "cut"), "the end record cut off"),
        array("FILE_README", README, "readme.txt"),
        array("FILE_A", A_TXT, "notes/a.txt"),
        array("FILE_B", B_TXT, "notes/b.txt"),
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n\n".join(parts) + "\n")
    print("wrote %s (%d bytes of archive)" % (OUT, len(g)))


if __name__ == "__main__":
    main()
