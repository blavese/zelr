/* What a page's context is given as script rather than natives, run as it
 * opens, before any of the page's scripts. Included from jsdom.h.
 *
 * Streams (WHATWG Streams), the readable kind: ReadableStream with its
 * default controller and reader, a source's start, pull and cancel, reading
 * through a reader or as an async iterator, tee, and pipeTo and pipeThrough
 * into anything with a writable side that has write and close.
 *
 * Pages build streams of their own -- X's first script makes one of the
 * answers its server is still sending, and React's server rendering reads
 * one -- and a page that finds no ReadableStream stops there.
 *
 * Kept as a script rather than natives because that is what it is: objects
 * and promises, and every value it holds lives where the collector looks
 * (jsgc.h), in the page's region, reached from the page's globals.
 *
 * Not done: byte streams (getReader({ mode: 'byob' })), queuing strategies'
 * sizes (a chunk counts one), WritableStream and TransformStream as classes,
 * and a fetch() answer's body as a stream.
 *
 * navigator.serviceWorker, which pages look in before they register one:
 * there is no controller, ready never settles, and register() is refused
 * with NotSupportedError, which is the truth -- no worker runs a page's
 * requests here. Bing's first script read navigator.serviceWorker.controller,
 * stopped on finding nothing to read it from, and everything after it went
 * without the names it defines.
 *
 * The handler properties every element, the document and the window have
 * (onclick, oninput and the rest of GlobalEventHandlers), null until set,
 * and an element's read from its attribute: they were there only once a
 * page had set one, so React, asking whether input events exist the way it
 * does ('oninput' in document, then an attribute on a div), decided they did
 * not and fell back on Internet Explorer's attachEvent, which stopped
 * DuckDuckGo's home page. Set, a handler is the object's own property, which
 * is where dispatch looks (jsdom.h). No touch handlers: a page reads
 * 'ontouchstart' in window as a touch screen. */

