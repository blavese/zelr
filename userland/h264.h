/* --- the picture around the slices ------------------------------------------------------- */

static void h264_finish_picture(h264_dec *d) {
    if (!d->cur) return;
    h264_deblock_picture(d);
    h264_mark(d);
    d->cur->wait_output = 1;
    d->prev_frame_num = d->sl.frame_num;
    if (d->sl.nal_ref_idc) d->prev_ref_frame_num = d->cur->frame_num;
    d->frames_decoded++;
    d->cur = 0;
}

/* frame_num jumped: the frames in between are made up so the sliding
   window counts right (8.2.5.2). */
static void h264_gaps(h264_dec *d) {
    int num = d->sl.frame_num, prev = d->prev_ref_frame_num;
    if (d->sl.idr || num == prev || num == (prev + 1) % d->max_frame_num) return;
    int guard = 0;
    for (int f = (prev + 1) % d->max_frame_num; f != num && guard < 16; f = (f + 1) % d->max_frame_num, guard++) {
        h264_pic *p = h264_free_frame(d);
        if (!p) return;
        p->in_use = 1;
        p->nonexisting = 1;
        p->frame_num = f;
        p->wait_output = 0;
        p->poc = 0;
        p->id = ++d->next_id;
        h264_slice keep_type;                  /* the sliding window reads frame_num through sl */
        (void)keep_type;
        int real = d->sl.frame_num;
        d->sl.frame_num = f;
        h264_pic *was = d->cur;
        d->cur = p;
        h264_frame_num_wrap(d);
        h264_sliding_window(d);
        p->ref = 1;
        d->cur = was;
        d->sl.frame_num = real;
        d->prev_ref_frame_num = f;
    }
}

static int h264_start_picture(h264_dec *d) {
    const h264_pps *pp = &d->pps[d->sl.pps_id];
    if (h264_activate(d, pp) < 0) return -1;
    if (d->sl.idr) {
        for (int i = 0; i < H264_DPB; i++) d->dpb[i].ref = 0;
        if (d->sl.no_output_prior) for (int i = 0; i < H264_DPB; i++) d->dpb[i].wait_output = 0;
        d->prev_ref_frame_num = 0;
        d->epoch++;
    } else {
        h264_gaps(d);
    }
    h264_pic *p = h264_free_frame(d);
    if (!p) { h264_say(d, "no free frame: more pictures kept than the stream said it would"); return -1; }
    p->in_use = 1;
    p->nonexisting = 0;
    p->ref = 0;
    p->wait_output = 0;
    p->idr_like = d->sl.idr;
    p->frame_num = d->sl.frame_num;
    p->id = ++d->next_id;
    p->lt_idx = 0;
    p->epoch = d->epoch;
    p->pts = d->next_pts;
    d->cur = p;
    p->poc = h264_poc(d);
    for (int i = 0; i < d->mbs; i++) d->mb_slice[i] = -1;
    d->slices = 0;
    return 0;
}

static int h264_slice_data(h264_dec *d, h264_bits *b);

static int h264_slice_nal(h264_dec *d, h264_bits *b, int nal_type, int nal_ref_idc) {
    /* Whether this slice begins a new picture is in its header (7.4.1.2.4);
       the header is read into a copy first so the old picture's state is
       still there to finish it with. */
    static h264_slice keep;
    for (int i = 0; i < (int)sizeof(keep); i++) ((volatile u8 *)&keep)[i] = ((u8 *)&d->sl)[i];
    if (h264_slice_header(d, b, nal_type, nal_ref_idc) < 0) return -1;
    if (d->sl.redundant_pic_cnt > 0) return 0;     /* the primary picture is enough */
    int newpic = !d->cur || d->sl.first_mb == 0 || d->sl.frame_num != keep.frame_num ||
                 d->sl.pps_id != keep.pps_id || (d->sl.nal_ref_idc != 0) != (keep.nal_ref_idc != 0) ||
                 d->sl.idr != keep.idr || (d->sl.idr && d->sl.idr_pic_id != keep.idr_pic_id) ||
                 d->sl.poc_lsb != keep.poc_lsb || d->sl.delta_poc_bottom != keep.delta_poc_bottom;
    if (newpic && d->cur) {
        /* Finish the last picture with the header it was decoded under. */
        static h264_slice now;
        for (int i = 0; i < (int)sizeof(now); i++) ((volatile u8 *)&now)[i] = ((u8 *)&d->sl)[i];
        for (int i = 0; i < (int)sizeof(keep); i++) ((volatile u8 *)&d->sl)[i] = ((u8 *)&keep)[i];
        h264_finish_picture(d);
        for (int i = 0; i < (int)sizeof(now); i++) ((volatile u8 *)&d->sl)[i] = ((u8 *)&now)[i];
    }
    if (newpic && h264_start_picture(d) < 0) return -1;
    if (d->pps[d->sl.pps_id].sps_id != d->pp->sps_id) { h264_say(d, "a slice changes sequence mid-picture"); return -1; }
    d->pp = &d->pps[d->sl.pps_id];
    d->sl.number = d->slices++;
    if (d->sl.type != H264_I && h264_init_lists(d) < 0) return -1;
    for (int l = 0; l < 2; l++)
        for (int i = 0; i < d->sl.num_ref[l]; i++)
            if (!d->sl.list[l][i]) {
                /* A missing reference: use any there is rather than stop
                   (a stream joined part way has them; the picture will be
                   wrong until the next IDR, not the decoder). */
                for (int k = 0; k < H264_DPB && !d->sl.list[l][i]; k++)
                    if (d->dpb[k].in_use && &d->dpb[k] != d->cur && !d->dpb[k].nonexisting) d->sl.list[l][i] = &d->dpb[k];
                if (!d->sl.list[l][i]) d->sl.list[l][i] = d->cur;
            }
    if (d->sl.type == H264_B && d->pp->weighted_bipred == 2) h264_implicit(d);
    {
        const h264_slice *s = &d->sl;
        d->seen |= d->pp->cabac ? H264_SEEN_CABAC : H264_SEEN_CAVLC;
        if (s->type == H264_B) d->seen |= H264_SEEN_B | (s->direct_spatial ? H264_SEEN_SPATIAL : H264_SEEN_TEMPORAL);
        if ((s->type == H264_P && d->pp->weighted_pred) || (s->type == H264_B && d->pp->weighted_bipred == 1)) {
            for (int l = 0; l < 2; l++)
                for (int i = 0; i < s->num_ref[l]; i++)
                    if (s->lwflag[l][i] || s->cwflag[l][i]) d->seen |= H264_SEEN_EXPLICIT;
        }
        if (s->type == H264_B && d->pp->weighted_bipred == 2) d->seen |= H264_SEEN_IMPLICIT;
        if (s->num_ref[0] > 1 || s->num_ref[1] > 1) d->seen |= H264_SEEN_MULTIREF;
        if (s->n_mmco || s->long_term_ref) d->seen |= H264_SEEN_MMCO;
        for (int l = 0; l < 2; l++)
            for (int i = 0; i < s->num_ref[l]; i++)
                if (s->list[l][i] && s->list[l][i]->ref == 2) d->seen |= H264_SEEN_LONGTERM;
        if (d->pp->scaling_present || d->sp->scaling_present) d->seen |= H264_SEEN_SCALING;
        if (s->number > 0) d->seen |= H264_SEEN_SLICES;
    }
    return h264_slice_data(d, b);
}

/* --- NAL units ------------------------------------------------------------------------------- */

/* One NAL unit, without its start code. */
static int h264_nal(h264_dec *d, const u8 *p, int n) {
    if (n < 1) return 0;
    int type = p[0] & 31, ref_idc = (p[0] >> 5) & 3;
    if (type != 1 && type != 5 && type != 7 && type != 8) {
        if (type == 11 || type == 10) { /* end of stream or sequence: nothing to keep */ }
        if (type == 2 || type == 3 || type == 4) { h264_say(d, "data partitioning, which this does not decode"); return -1; }
        return 0;
    }
    if (d->rbsp_cap < n) {
        if (d->rbsp) h264_free(d->rbsp);
        d->rbsp_cap = n + 1024;
        d->rbsp = (u8 *)h264_alloc((u64)d->rbsp_cap);
        if (!d->rbsp) { d->rbsp_cap = 0; h264_say(d, "not enough memory for a NAL unit"); return -1; }
    }
    int m = 0, zeros = 0;
    for (int i = 1; i < n; i++) {
        if (zeros >= 2 && p[i] == 3) { zeros = 0; continue; }
        zeros = p[i] ? 0 : zeros + 1;
        d->rbsp[m++] = p[i];
    }
    h264_bits b = { d->rbsp, m, 0 };
    if (type == 7) return h264_parse_sps(d, &b);
    if (type == 8) return h264_parse_pps(d, &b);
    return h264_slice_nal(d, &b, type, ref_idc);
}

/* Whether a frame is due, and its time, without taking it: a player holds
   it in the decoder until the sound reaches it. */
__attribute__((unused)) static int h264_peek(h264_dec *d, long long *pts) {
    if (!h264_due(d)) return 0;
    h264_pic *p = h264_next_out(d);
    if (!p) return 0;
    *pts = p->pts;
    return 1;
}

/* The next frame due for showing, or 0. */
static int h264_frame(h264_dec *d, h264_picture *out) {
    if (d->shown) { d->shown = 0; h264_release(d); }
    if (!h264_due(d)) return 0;
    h264_pic *p = h264_next_out(d);
    if (!p) return 0;
    p->wait_output = 0;
    d->shown = p;
    d->frames_out++;
    const h264_sps *sp = d->sp;
    int w = d->mb_w * 16;
    out->stride_y = w;
    out->stride_c = w / 2;
    out->y = p->y + sp->crop_t * w + sp->crop_l;
    out->cb = p->cb + (sp->crop_t / 2) * (w / 2) + sp->crop_l / 2;
    out->cr = p->cr + (sp->crop_t / 2) * (w / 2) + sp->crop_l / 2;
    out->width = w - sp->crop_l - sp->crop_r;
    out->height = d->mb_h * 16 - sp->crop_t - sp->crop_b;
    out->poc = p->poc;
    out->pts = p->pts;
    out->full_range = sp->full_range;
    out->matrix = sp->matrix;
    return 1;
}

/* The end of the stream: the last picture finished and everything waiting
   made due. */
static void h264_flush(h264_dec *d) {
    if (d->cur) h264_finish_picture(d);
    d->flushing = 1;
}

/* The next NAL unit of an Annex B buffer after *at: its start and length
   (trailing zero bytes left out); 0 when there are no more. */
__attribute__((unused)) static int h264_next_nal(const u8 *p, int n, int *at, int *start, int *len) {
    int i = *at;
    while (i + 3 <= n && !(p[i] == 0 && p[i + 1] == 0 && p[i + 2] == 1)) i++;
    if (i + 3 > n) { *at = n; return 0; }
    int s = i + 3, e = s;
    while (e + 3 <= n && !(p[e] == 0 && p[e + 1] == 0 && p[e + 2] == 1)) e++;
    if (e + 3 > n) e = n;
    *at = e;
    while (e > s && p[e - 1] == 0) e--;
    *start = s;
    *len = e - s;
    return 1;
}

/* How many more pictures can be decoded before a frame has to be taken.
   A caller that holds frames back (to show them on time) decodes only
   while this is above 0, and takes the frames that are due in between. */
__attribute__((unused)) static int h264_room(h264_dec *d) {
    if (!d->npics) return 1;                   /* nothing yet: the first picture makes them */
    h264_release(d);
    int n = 0;
    for (int i = 0; i < d->npics; i++) if (!d->dpb[i].in_use) n++;
    return n;
}

/* A whole access unit (a transport stream's PES packet) and its time. Its
   picture is begun while pts is the time given to it; the picture is
   finished, and becomes due for showing, when the next one begins (or at
   h264_flush). */
__attribute__((unused)) static int h264_decode_au(h264_dec *d, const u8 *p, int n, long long pts) {
    d->next_pts = pts;
    int at = 0, s, len, bad = 0;
    while (h264_next_nal(p, n, &at, &s, &len))
        if (h264_nal(d, p + s, len) < 0) bad = 1;
    return bad ? -1 : 0;
}

static void h264_open(h264_dec *d) {
    for (int i = 0; i < (int)sizeof(*d); i++) ((volatile u8 *)d)[i] = 0;
    d->max_lt_idx = -1;
}

__attribute__((unused)) static void h264_close(h264_dec *d) {
    h264_free_pics(d);
    if (d->rbsp) h264_free(d->rbsp);
    d->rbsp = 0;
}
