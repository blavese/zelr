/* An H.264 (AVC) decoder, written from ITU-T H.264.
 *
 * What a live stream sends: Baseline, Main and High profile, progressive
 * frames in 4:2:0 at 8 bits, CAVLC or CABAC, I, P and B slices with any
 * number of slices a picture, weighted prediction (explicit and implicit),
 * spatial and temporal direct, the 8x8 transform and scaling matrices,
 * long-term references and memory management, and output in display order.
 * Refused by name rather than decoded wrongly: fields (PAFF and MBAFF),
 * other chroma formats and bit depths, slice groups, data partitioning,
 * and SP and SI slices.
 *
 * Feed it access units (h264_decode_au, a transport stream's PES packets)
 * or NAL units (h264_nal, h264_next_nal splitting an Annex B buffer), and
 * take frames from it (h264_frame) as they become due, before decoding
 * more once h264_room says there is no frame free; h264_flush makes the
 * rest due at the end. A picture is the planes of the frame it decoded
 * into, valid until the next call to h264_frame.
 *
 * The numbers (CABAC contexts, variable-length codes, scans, filter
 * thresholds) are in h264tab.h, generated by tools/mkh264.py from ITU-T's
 * reference decoder. The parts are h264mb.h (entropy decoding of a
 * macroblock) and h264rec.h (prediction, the transforms and the deblocking
 * filter); this file is the stream around them.
 */
#pragma once
#ifndef H264_NO_ZELR
#include "zelr.h"
#include "alloc.h"
#define h264_alloc(n) calloc(n)
#define h264_free(p) free(p)
#endif
#include "h264tab.h"

#define H264_MAX_SPS 32
#define H264_MAX_PPS 256
#define H264_MAX_LIST 32
#define H264_DPB 18                    /* sixteen references, the current one and one waiting */

typedef struct {
    int present;
    int profile_idc, level_idc, chroma_format_idc;
    int bit_depth_luma, bit_depth_chroma, bypass;
    int log2_max_frame_num, poc_type, log2_max_poc_lsb;
    int delta_pic_order_always_zero, offset_for_non_ref_pic, offset_for_top_to_bottom_field;
    int poc_cycle, offset_for_ref_frame[256];
    int max_num_ref_frames, gaps_allowed;
    int mb_w, mb_h, frame_mbs_only, mbaff, direct_8x8_inference;
    int crop_l, crop_r, crop_t, crop_b;        /* in luma samples */
    int scaling_present;
    u8 sl4[6][16], sl8[2][64];                 /* raster order */
    int num_reorder, max_dec_buffering;        /* -1 when the stream does not say */
    int full_range, matrix;
} h264_sps;

typedef struct {
    int present, sps_id, cabac, bottom_field_poc, slice_groups;
    int num_ref_idx_default[2], weighted_pred, weighted_bipred;
    int init_qp, init_qs, chroma_qp_offset[2], deblock_control, constrained_intra, redundant_pic_cnt;
    int transform_8x8, scaling_present;
    u8 sl4[6][16], sl8[2][64];                 /* raster order, after the fall-back rules */
} h264_pps;

typedef struct h264_pic {
    u8 *y, *cb, *cr;
    short (*mv)[2][16][2];                     /* each macroblock's 4x4 blocks, raster order */
    signed char (*ri)[2][4];                   /* each 8x8's reference index, -1 none */
    int (*refid)[2][4];                        /* and the picture it is, by id */
    u8 *intra;
    int poc, frame_num, frame_num_wrap, lt_idx;
    int ref;                                   /* 0 none, 1 short-term, 2 long-term */
    int wait_output, id, nonexisting, in_use;
    int idr_like;                              /* an IDR or after memory management 5 */
    int epoch;                                 /* which run of picture order it belongs to */
    long long pts;                             /* the time its access unit carried */
} h264_pic;

enum { H264_P = 0, H264_B = 1, H264_I = 2, H264_SP = 3, H264_SI = 4 };

typedef struct {
    int first_mb, type, pps_id, frame_num, idr, idr_pic_id, nal_ref_idc, nal_type;
    int poc_lsb, delta_poc_bottom, delta_poc[2], redundant_pic_cnt;
    int direct_spatial, num_ref[2], cabac_init_idc, qp, deblock_idc, alpha_off, beta_off;
    int long_term_ref, no_output_prior, adaptive_marking, n_mmco, mmco[72][3];
    int mod[2][33][2], n_mod[2];
    int luma_denom, chroma_denom;
    short lw[2][H264_MAX_LIST], lo[2][H264_MAX_LIST], cw[2][H264_MAX_LIST][2], co[2][H264_MAX_LIST][2];
    u8 lwflag[2][H264_MAX_LIST], cwflag[2][H264_MAX_LIST];
    h264_pic *list[2][H264_MAX_LIST + 1];       /* one longer: a change inserts before it removes */
    short implicit[H264_MAX_LIST][H264_MAX_LIST]; /* w1 of implicit weights; w0 = 64 - w1 */
    int number;                                /* this slice's number in its picture */
} h264_slice;

/* What a decoded frame is, for whoever shows it. */
typedef struct {
    const u8 *y, *cb, *cr;
    int stride_y, stride_c;                    /* in bytes */
    int width, height;                         /* after cropping */
    int poc, full_range, matrix;
    long long pts;                             /* as given to h264_decode_au with its access unit */
} h264_picture;

typedef struct h264_bits { const u8 *p; int n, pos; } h264_bits;

typedef struct h264_dec h264_dec;

/* The macroblock being decoded: what its syntax said, before it is
   predicted and its residual added. Coefficients are kept in raster order
   within their block, already dequantised. */
typedef struct {
    int addr, x, y;                            /* address, and column and row in macroblocks */
    int kind;                                  /* H264_K_* */
    int i16mode, cbp, t8, qp, cpred;
    int parts;                                 /* 1 (16x16), 2 (16x8), 3 (8x16) or 4 (8x8) */
    int pred[4];                               /* each partition: bit 0 list 0, bit 1 list 1 */
    int sub[4];                                /* each 8x8: sub-partitions, 1, 2 (8x4), 3 (4x8) or 4 */
    int subpred[4];
    int ref[2][4];                             /* each 8x8's reference index, as sent */
    int no_small;                              /* no partition smaller than 8x8 (the 8x8 transform's condition) */
    short mvd[2][16][2];                       /* each 4x4 block's (raster) mvd */
    signed char ipm[16];                       /* each 4x4 block's intra mode (raster) */
    int coded;                                 /* luma 4x4 blocks with coefficients, by raster bit */
    int dc_coded, cdc_coded, cac_coded;        /* luma DC; chroma DC by component; chroma AC by bit */
    short coef[16][16];
    short coef8[4][64];
    short dc[16];
    short cdc[2][4];
    short cac[2][4][16];
    u8 pcm[384];
    u16 done;                                  /* 4x4 blocks whose motion is known, by raster bit */
} h264_mbctx;

